    @Test("Player input is distinguished by its countdown bar, not by the strip")
    func inputTimerBar() throws {
        let reader = SlotStripReader()
        let input = try reader.read(band("Phases/field-00492.png")).get()
        // The strip itself looks exactly like a presentation: four indicators
        // with the first selected. Only the bar separates the two screens.
        #expect(input.slotCount == 4)
        #expect(input.highlightedIndex == 0)
        #expect(input.hasInputTimerBar)

        let recordingInput = try reader.read(band("Recording/sample-28550.png")).get()
        #expect(recordingInput.hasInputTimerBar)
        // Later in player input the gold portion has shrunk and both violet
        // ends are exposed. The complete track is still evidence of input.
        #expect(reader.hasTimerBar(try band("Frames/frame-02690.jpg")))
    }

    @Test("Captured countdown remains readable with the entire indicator strip covered")
    func timerWithoutIndicators() throws {
        let original = try band("Phases/field-00492.png")
        var pixels = original.image.pixels
        let layout = GameUILayout()
        for y in original.rows(layout.headerTextTop, layout.slotStripBottom) {
            for x in 0..<original.image.width {
                let offset = (y * original.image.width + x) * 3
                pixels[offset] = 0; pixels[offset + 1] = 0; pixels[offset + 2] = 0
            }
        }
        let covered = FrameTopBand(image: try ColorImage(width: original.image.width,
            height: original.image.height, pixels: pixels), frameHeight: original.frameHeight)
        let reader = SlotStripReader()
        #expect(throws: SlotStripRejection.self) { try reader.read(covered).get() }
        #expect(reader.hasTimerBar(covered))
        #expect(!reader.hasTimerBar(try band("Phases/field-00443.png")))
    }

