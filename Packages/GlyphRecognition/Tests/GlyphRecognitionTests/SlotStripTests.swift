/// Pixel tests for the evidence that makes a sequence collectable at all.
///
/// The expected answers are the visible screens, read by eye from the fixtures
/// listed in `Fixtures/Assets/Screenshots/Phases/README.md`, `Fixtures/Assets/Screenshots/Recording/README.md`,
/// `Fixtures/Assets/Screenshots/Banner/README.md`, `Fixtures/Assets/Screenshots/Covered/README.md`,
/// `Fixtures/Assets/Screenshots/WindowEdge/README.md` and `Fixtures/Assets/Screenshots/OneGlyph/README.md`.
/// The separate synthetic clutter case uses hand-specified pixel coordinates.
/// Nothing here is generated by the reader it checks.
@Suite("Slot indicator strip")
struct SlotStripTests {
    private func band(_ path: String) throws -> FrameTopBand {
        let url = try ReferenceData.fixturesDirectory.appendingPathComponent(path)
        let data = try Data(contentsOf: url)
        guard let source = CGImageSourceCreateWithData(data as CFData, nil),
              let image = CGImageSourceCreateImageAtIndex(source, 0, nil) else {
            throw CocoaError(.fileReadCorruptFile)
        }
        return try ImageDecoder.topBand(image)
    }

    @Test("The field presentation shows four indicators and the highlight advances")
    func fieldPresentation() throws {
        let reader = SlotStripReader()
        // Samples 443, 456 and 472 of the first field run: the first presented
        // shape, and the blanks after the second and fourth.
        for (file, expected) in [("Phases/field-00443.png", 0),
                                 ("Phases/field-00456.png", 1),
                                 ("Phases/field-00472.png", 3)] {
            let reading = try reader.read(band(file)).get()
            #expect(reading.slotCount == 4)
            #expect(reading.highlightedIndex == expected)
            #expect(!reading.hasInputTimerBar)
            #expect(!reading.isPartlyCovered)
        }
    }

    @Test("Indicators under a notification banner are read below its edge")
    func underNotificationBanner() throws {
        let reader = SlotStripReader()
        // Samples of the 2026-09-23 field run with a message banner over the
        // header and the tops of all four indicators.
        for (file, highlight, timer) in [("Banner/banner-00554.png", 0, false),
                                         ("Banner/banner-00572.png", 2, false),
                                         ("Banner/banner-00580.png", 3, false),
                                         ("Banner/banner-02793.png", 0, false),
                                         ("Banner/banner-00603.png", 0, true)] {
            let reading = try reader.read(band(file)).get()
            #expect(reading.slotCount == 4, Comment(rawValue: file))
            #expect(reading.highlightedIndex == highlight, Comment(rawValue: file))
            #expect(reading.hasInputTimerBar == timer, Comment(rawValue: file))
            #expect(reading.isPartlyCovered, Comment(rawValue: file))
        }
    }

    /// Four violet outlined indicators, centred at the measured pitch, with a
    /// grey banner from the top of the band down to `bannerBottom`. Coordinates
    /// are authored independently of `GameUILayout`.
    private func bannerBand(bannerBottom: Int, bannerLeft: Int = 10, bannerRight: Int = 593,
                            highlighted: Int? = nil) throws -> FrameTopBand {
        let width = 603, height = 323
        var pixels = [UInt8](repeating: 0, count: width * height * 3)
        for index in 0..<4 {
            let center = 301 + (2 * index - 3) * 48
            for y in 145..<225 {
                for x in (center - 40)..<(center + 40) {
                    if y >= 149 && y < 221 && x >= center - 36 && x < center + 36 { continue }
                    let offset = (y * width + x) * 3
                    let color: [UInt8] = index == highlighted ? [240, 180, 50] : [185, 165, 240]
                    pixels.replaceSubrange(offset..<(offset + 3), with: color)
                }
            }
        }
        for y in 60..<bannerBottom {
            for x in bannerLeft..<bannerRight {
                let offset = (y * width + x) * 3
                pixels.replaceSubrange(offset..<(offset + 3), with: [128, 130, 135])
            }
        }
        return FrameTopBand(image: try ColorImage(width: width, height: height, pixels: pixels), frameHeight: 1311)
    }

    @Test("A banner over the tops of the indicators leaves the row readable")
    func syntheticBanner() throws {
        let reading = try SlotStripReader().read(bannerBand(bannerBottom: 175)).get()
        #expect(reading.slotCount == 4)
        #expect(reading.highlightedIndex == nil)
        #expect(reading.isPartlyCovered)
    }

    @Test("A banner that leaves too little of the indicators, or all of the strip, is rejected",
          arguments: [205, 226, 240])
    func bannerTooLow(bottom: Int) throws {
        #expect(throws: SlotStripRejection.self) { try SlotStripReader().read(bannerBand(bannerBottom: bottom)).get() }
    }

    @Test("A presentation that starts under a banner is collected from its indicators")
    func presentationUnderBanner() throws {
        let session = CaptureSessionID(rawValue: 7)
        let reader = SlotStripReader()
        let blank = ShapeEvidence(kind: .noStroke, glyph: nil, edges: [], extensions: [])
        let shown = ShapeEvidence(kind: .uniqueVisibleShape, glyph: GlyphID("test"), edges: [], extensions: [])
        var tracker = PresentationTracker(sessionID: session)
        let frames: [(Int?, ShapeEvidence)] = [(nil, blank), (nil, blank), (nil, blank),
                                               (0, shown), (0, shown), (0, shown), (1, blank)]
        for (index, (highlight, shape)) in frames.enumerated() {
            let band = try bannerBand(bannerBottom: 175, highlighted: highlight)
            // The header is under the banner too: no text evidence at all.
            _ = tracker.accept(FrameEvidence(sessionID: session, time: 1 + Double(index) * 0.05,
                                             header: nil, slots: try reader.read(band).get(),
                                             shape: shape, hasValidCalibration: true,
                                             hasInputTimerBar: reader.hasTimerBar(band)))
        }
        #expect(tracker.state == .presenting)
        #expect(tracker.phaseSource == .indicatorTransition)
        #expect(tracker.expectedSlotCount == 4)
        #expect(tracker.confirmedPrefix == [GlyphID("test")])
    }

    @Test("A window whose lower edge crosses the strip is reported as covering it")
    func windowOverStrip() throws {
        #expect(SlotStripReader().read(try band("Covered/window-00407.png")) == .failure(.coveredByOverlay))

        // The same shape, authored by hand: a dark window with a lit border
        // across the strip, leaving only the bottom of the indicators.
        let width = 603, height = 323
        var pixels = [UInt8](repeating: 0, count: width * height * 3)
        func fill(_ ys: Range<Int>, _ xs: Range<Int>, _ color: [UInt8]) {
            for y in ys { for x in xs {
                let offset = (y * width + x) * 3
                pixels.replaceSubrange(offset..<(offset + 3), with: color)
            } }
        }
        for index in 0..<4 {
            let center = 301 + (2 * index - 3) * 48
            fill(210..<225, (center - 40)..<(center - 36), [185, 165, 240])
            fill(210..<225, (center + 36)..<(center + 40), [185, 165, 240])
            fill(221..<225, (center - 40)..<(center + 40), [185, 165, 240])
        }
        fill(80..<200, 20..<583, [8, 12, 18])
        fill(200..<208, 20..<583, [78, 80, 90])
        let covered = FrameTopBand(image: try ColorImage(width: width, height: height, pixels: pixels),
                                   frameHeight: 1311)
        #expect(SlotStripReader().read(covered) == .failure(.coveredByOverlay))
    }

    @Test("A window whose border only touches the top of the strip leaves the row readable")
    func windowAboveStrip() throws {
        // Like the 2026-09-22 run: a thin window just above the indicators.
        let width = 603, height = 323
        var pixels = [UInt8](repeating: 0, count: width * height * 3)
        for index in 0..<4 {
            let center = 301 + (2 * index - 3) * 48
            for y in 145..<225 {
                for x in (center - 40)..<(center + 40) {
                    if y >= 149 && y < 221 && x >= center - 36 && x < center + 36 { continue }
                    let offset = (y * width + x) * 3
                    pixels.replaceSubrange(offset..<(offset + 3), with: [185, 165, 240])
                }
            }
        }
        for y in 130..<139 {
            for x in 20..<583 {
                let offset = (y * width + x) * 3
                pixels.replaceSubrange(offset..<(offset + 3), with: y < 137 ? [78, 80, 90] : [8, 12, 18])
            }
        }
        let band = FrameTopBand(image: try ColorImage(width: width, height: height, pixels: pixels), frameHeight: 1311)
        let reading = try SlotStripReader().read(band).get()
        #expect(reading.slotCount == 4)
        #expect(!reading.isPartlyCovered)
    }

    @Test("Indicators under the floating window's coloured edge are read below it")
    func underWindowEdge() throws {
        let reader = SlotStripReader()
        // The 2026-09-25 report: the window's lower edge lies across the tips
        // of all three indicators, teal while collecting, lavender while the
        // player draws.
        for (file, highlight, timer) in [("WindowEdge/edge-00159.png", 0, false),
                                         ("WindowEdge/edge-00236.png", 2, true)] {
            let reading = try reader.read(band(file)).get()
            #expect(reading.slotCount == 3, Comment(rawValue: file))
            #expect(reading.highlightedIndex == highlight, Comment(rawValue: file))
            #expect(reading.hasInputTimerBar == timer, Comment(rawValue: file))
            #expect(reading.isPartlyCovered, Comment(rawValue: file))
        }
        // The same window over a Glyph screen with no strip hides nothing:
        // saying it covers the strip would ask the player to move it.
        #expect(reader.read(try band("WindowEdge/edge-00088.png")) == .failure(.noMarkers))
    }

    @Test("A one-Glyph hack's single indicator is read below the floating window")
    func singleIndicator() throws {
        let reader = SlotStripReader()
        // The 2026-10-05 field test: a level 1 portal, the window just above
        // the strip, the header under it.
        let waiting = try reader.read(band("OneGlyph/one-01868.png")).get()
