        for file in ["Phases/field-00381.png",   // command channel
                     "Phases/field-00615.png",   // completion dialog
                     "Phases/field-00666.png",   // redacted map; much of this band is masked
                     "Recording/sample-23600.png"] {
            let result = reader.read(try band(file))
            #expect(throws: SlotStripRejection.self, Comment(rawValue: file)) { try result.get() }
        }
    }

    @Test("Gold and violet clutter is rejected for uneven geometry, not absent ink")
    func rejectsColoredClutter() throws {
        let width = 603, height = 323
        var pixels = [UInt8](repeating: 0, count: width * height * 3)
        // Three outlined boxes of plausible marker size and height, but with
        // unequal gaps. Pixel positions and colors are authored independently
        // of GameUILayout and SlotStripReader's thresholds.
        for (index, left) in [40, 170, 440].enumerated() {
            let color: [UInt8] = index == 0 ? [230, 180, 40] : [185, 165, 240]
            for y in 150..<220 {
                for x in left..<(left + 70) {
                    guard y < 154 || y >= 216 || x < left + 4 || x >= left + 66 else { continue }
                    let offset = (y * width + x) * 3
                    pixels.replaceSubrange(offset..<(offset + 3), with: color)
                }
            }
        }
        let band = FrameTopBand(image: try ColorImage(width: width, height: height, pixels: pixels),
                                frameHeight: 1311)
        switch SlotStripReader().read(band) {
        case .failure(let reason): #expect(reason == .unevenSpacing)
        case .success: Issue.record("Colored clutter was accepted as a game indicator strip")
        }
    }

    @Test("The measured layout keeps the header, the strip and the array apart")
    func layoutMeasurements() throws {
        let layout = GameUILayout()
        #expect(layout.headerTextBottom <= layout.slotStripTop)
        #expect(layout.slotStripBottom <= layout.inputTimerBarTop)
        // The fitted array must sit clear of everything read from the top band,
        // or these fractions are describing some other screen.
        // A blank presentation frame: the rings are clear, which is the only
        // state the detector is meant to calibrate from.
        let url = try ReferenceData.fixturesDirectory.appendingPathComponent("Phases/field-00456.png")
        let frame = try ImageDecoder.load(url)
        let fit = try #require(NodeArrayDetector().detect(in: frame))
        #expect(layout.isConsistent(with: fit))
        #expect(fit.origin.y > layout.topBandBottom * Double(frame.height))
    }
