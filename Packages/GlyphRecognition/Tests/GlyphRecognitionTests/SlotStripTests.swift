    @Test("A lone marker off the screen's centre is not a one-slot strip")
    func singleMarkerOffCentre() throws {
        let width = 603, height = 323
        var pixels = [UInt8](repeating: 0, count: width * height * 3)
        // One outlined box of plausible marker size and height, a quarter of
        // the way across: a strip of any length centres its only indicator.
        // Authored like the clutter case, independently of the reader.
        let left = 120
        for y in 150..<220 {
            for x in left..<(left + 70) {
                guard y < 154 || y >= 216 || x < left + 4 || x >= left + 66 else { continue }
                let offset = (y * width + x) * 3
                pixels.replaceSubrange(offset..<(offset + 3), with: [185, 165, 240])
            }
        }
        let band = FrameTopBand(image: try ColorImage(width: width, height: height, pixels: pixels),
                                frameHeight: 1311)
        switch SlotStripReader().read(band) {
        case .failure(let reason): #expect(reason == .incompleteStrip)
        case .success: Issue.record("A lone off-centre marker was accepted as a one-slot strip")
        }
    }

    @Test("A presentation seen only through the indicators survives the window edge turning teal")
    func presentationUnderWindowEdge() throws {
        let session = CaptureSessionID(rawValue: 9)
        let reader = SlotStripReader()
        let teal = try band("WindowEdge/edge-00159.png")
        let first = try reader.read(teal).get()
        let blank = ShapeEvidence(kind: .noStroke, glyph: nil, edges: [], extensions: [])
        let shown = ShapeEvidence(kind: .uniqueVisibleShape, glyph: GlyphID("discover"), edges: [], extensions: [])
        var tracker = PresentationTracker(sessionID: session)
        // The empty strip before the first Glyph, and the first highlighted
        // frame, read before the edge changed colour. The header was never
        // readable in the report, so there is no text evidence at all.
        let prelude = SlotStripReading(slotCount: 3, highlightedIndex: nil,
                                       markerCentersX: first.markerCentersX, hasInputTimerBar: false)
        for (index, (reading, shape)) in [(prelude, blank), (prelude, blank), (first, shown)].enumerated() {
            _ = tracker.accept(FrameEvidence(sessionID: session, time: 7.76 + Double(index) * 0.05,
                                             header: nil, slots: reading, shape: shape,
                                             hasValidCalibration: true))
        }
        #expect(tracker.state == .presenting)
        // The next frame is the captured one, the edge now teal.
        _ = tracker.accept(FrameEvidence(sessionID: session, time: 7.91, header: nil,
                                         slots: try reader.read(teal).get(), shape: shown,
                                         hasValidCalibration: true, hasInputTimerBar: reader.hasTimerBar(teal)))
        #expect(tracker.state == .presenting)
        #expect(tracker.phaseSource == .indicatorTransition)
        #expect(tracker.expectedSlotCount == 3)
        #expect(tracker.currentSlotIndex == 0)
    }

